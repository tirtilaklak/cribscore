import {readFile,writeFile,mkdir,readdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {build} from 'esbuild';

const root=fileURLToPath(new URL('../',import.meta.url));
const type={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8','.json':'application/json; charset=utf-8','.svg':'image/svg+xml'};
const files=[];
async function walk(path=''){
  for(const entry of (await readdir(`${root}dist/${path}`,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))){
    if(entry.name.startsWith('.')||(!path&&entry.name==='server'))continue;
    const relative=path+entry.name;
    if(entry.isDirectory())await walk(relative+'/');else if(entry.isFile())files.push(relative);else throw Error(`Unsupported public asset: ${relative}`);
  }
}
await walk();
const assets={},manifest=[];
for(const path of files){
  const extension=path.slice(path.lastIndexOf('.'));if(!type[extension])throw Error(`Unrecognized public asset type: ${path}`);
  const bytes=await readFile(`${root}dist/${path}`);const body=new TextDecoder('utf-8',{fatal:true}).decode(bytes);
  if(bytes.length>2_000_000)throw Error(`Public asset exceeds size limit: ${path}`);
  assets['/'+path]={type:type[extension],body};manifest.push({path:`dist/${path}`,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')});
}
if(!assets['/index.html']||!assets['/app.js'])throw Error('Required public entrypoint missing');
await mkdir(`${root}worker`,{recursive:true});await mkdir(`${root}dist/server`,{recursive:true});await mkdir(`${root}dist/.openai`,{recursive:true});
await writeFile(`${root}worker/generated-assets.js`,`// Generated by scripts/build-worker.mjs.\nexport const publicAssets=${JSON.stringify(assets)};\n`);
const result=await build({absWorkingDir:root,entryPoints:['worker/index.js'],outfile:'dist/server/index.js',bundle:true,format:'esm',platform:'browser',target:'es2022',minify:false,sourcemap:false,legalComments:'none',metafile:true});
const hosting=JSON.parse(await readFile(`${root}.openai/hosting.json`,'utf8'));
if(hosting.static||hosting.d1!=='DB')throw Error('Worker hosting must use the existing project and DB binding');
await writeFile(`${root}dist/.openai/hosting.json`,JSON.stringify(hosting,null,2)+'\n');
for(const input of Object.keys(result.metafile.inputs))if(/(^|\/)(tests?|fixtures?)(\/|$)|\.test\.[cm]?js$/.test(input))throw Error(`Test-only module cannot enter the production Worker: ${input}`);
const sourcePaths=[...Object.keys(result.metafile.inputs),'scripts/build-worker.mjs','scripts/validate-worker.mjs','package.json','package-lock.json','.openai/hosting.json'];
for(const file of await readdir(`${root}drizzle`))if(file.endsWith('.sql'))sourcePaths.push(`drizzle/${file}`);
for(const file of await readdir(`${root}drizzle/meta`))sourcePaths.push(`drizzle/meta/${file}`);
const sourceFiles={};for(const path of [...new Set(sourcePaths)].sort())sourceFiles[path]=createHash('sha256').update(await readFile(`${root}${path}`)).digest('hex');
await mkdir(`${root}docs`,{recursive:true});
await writeFile(`${root}docs/worker-build-manifest.json`,JSON.stringify({schemaVersion:1,publicAssets:manifest,bundle:{path:'dist/server/index.js',sha256:createHash('sha256').update(await readFile(`${root}dist/server/index.js`)).digest('hex')},sourceFiles},null,2)+'\n');
console.log(`Built Worker with ${manifest.length} embedded public assets.`);
